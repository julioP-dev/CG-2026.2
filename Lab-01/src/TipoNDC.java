/**
 * Representa os dois sistemas de coordenadas NDC utilizados
 * no laboratório.
 */
public enum TipoNDC {

    /**
     * Sistema NDC definido no intervalo:
     *
     * [0,1] x [0,1]
     */
    ZERO_A_UM,

    /**
     * Sistema NDC definido no intervalo:
     *
     * [-1,1] x [-1,1]
     */
    MENOS_UM_A_UM
}